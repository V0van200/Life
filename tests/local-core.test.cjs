const assert=require('node:assert/strict');
const L=require('../assets/life-core.js');
assert.equal(L.nextDue('2026-01-31','monthly',1),'2026-02-28');
assert.equal(L.nextDue('2026-01-31','monthly',2),'2026-03-31');
assert.equal(L.nextDue('2024-02-29','yearly',4),'2028-02-29');
assert.equal(L.nextDue('2026-01-01','30days',2),'2026-03-02');
assert.equal(L.occupiedMinutes([{start:'10:00',end:'12:00'},{start:'11:00',end:'13:00'}]),180);
assert.throws(()=>L.parseDay('2026-02-31'));
assert.throws(()=>L.validateRecord({id:"'bad",kind:'task',title:'x',date:'2026-10-25',amount:0}));
assert.equal(L.projectProgress([{kind:'task',projectId:'p',done:true},{kind:'task',projectId:'p',done:false}],'p').percent,50);
const service={kind:'subscription',id:'s',date:'2026-01-31',repeat:'monthly'};
assert.equal(L.upcoming([service,{paymentKey:'s:2026-02-28'}],'2026-02-01','2026-03-31')[0].paid,true);
assert.equal(L.upcoming([{...service,archived:true}],'2026-02-01','2026-03-31').length,0);
console.log('10 domain assertions passed');
